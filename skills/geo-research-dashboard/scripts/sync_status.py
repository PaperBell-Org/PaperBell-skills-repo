def date_near(lines: list, idx: int, year: int) -> str:
    """Walk upwards to the nearest dated heading or paragraph-opening line."""
    lo = max(-1, idx - 80)
    for j in range(idx, lo, -1):
        raw = lines[j]
        h = heading_of(raw)
        probe = None
        if h:
            probe = h[1]
        else:
            s = strip_marks(raw)
            if re.match(r"^(?:\d{4}-)?\d{1,2}-\d{1,2}(?![\d-])", s) or MONNAME_RE.match(s):
                probe = s
        if not probe:
            continue
        d, _ = parse_date(probe)
        if d:
            return d.isoformat()
        m = MONNAME_RE.search(probe[:60])
        if m:
            day = m.group(1) or m.group(4)
            mon = MONTHS[(m.group(2) or m.group(3)).lower()[:3]]
            try:
                return dt.date(year, mon, int(day)).isoformat()
            except ValueError:
                pass
        m = MD_RE.search(probe[:60])
        if m and 1 <= int(m.group(1)) <= 12 and 1 <= int(m.group(2)) <= 31:
            return f"{year:04d}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
    return ""


def paren_split(s: str, seps="；;") -> list:
    out, buf, depth = [], [], 0
    for ch in s:
        if ch in "（([【":
            depth += 1
        elif ch in "）)]】":
            depth = max(0, depth - 1)
        if ch in seps and depth == 0:
            out.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    out.append("".join(buf))
    return [x.strip() for x in out if x.strip()]


def split_inline(text: str) -> list:
    """Split several decisions on one line: `1) ... 2) ...` or `...; ...; ...`."""
    text = text.strip()
    marks = list(re.finditer(r"(?:(?<=^)|(?<=[；;。.\s]))[（(]?(\d{1,2})[)）]\s*", text))
    if len(marks) >= 2:
        parts = []
        for i, m in enumerate(marks):
            end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            parts.append(text[m.end():end].strip(" ；;"))
        return [p for p in parts if p]
    pieces = paren_split(text)
    if len(pieces) >= 2 and all(len(p) >= 6 for p in pieces):
        return pieces
    return [text] if text else []


def judge_none(text: str):
    """Return (said_none, remainder)."""
    orig = text.strip()
    t = orig.strip("*_ ")
    if not t:
        return False, ""
    if NONE_ITEM.match(t):
        return True, ""
    m = NONE_LEAD.match(t)
    if m:
        return False, m.group(1).strip()
    return False, orig


BULLET_RE = r"^\s*(?:>\s*)?(?:[-*+]|\d+[.)、）]|[（(]\d+[)）])\s+"


def block_after(ctx: Ctx, lines: list, i: int, stop_at_heading=True):
    """Field block after label line lines[i].

    - label line is itself a list item: take only more-indented lines;
    - otherwise: take list items and their continuation lines, stop at the
      first plain prose line;
    - stop at a heading, a known label line or a blank line.
    """
    lab = lines[i]
    lab_indent = len(lab) - len(lab.lstrip())
    lab_bullet = bool(re.match(BULLET_RE, lab))
    out = []
    j = i + 1
    while j < len(lines):
        ln = lines[j]
        if not ln.strip():
            break
        if stop_at_heading and heading_of(ln):
            break
        if is_known_label_line(ctx, ln):
            break
        indent = len(ln) - len(ln.lstrip())
        is_b = bool(re.match(BULLET_RE, ln))
        if lab_bullet:
            if indent <= lab_indent:
                break
        elif not is_b and indent == 0:
            break
        out.append(ln)
        j += 1
    return out, j


def items_from_block(block: list, first_line_no: int) -> list:
    items: list = []
    for k, ln in enumerate(block):
        s = ln.rstrip()
        bullet = re.match(BULLET_RE + r"(.*)$", s)
        indented = s[:1] in (" ", "\t") and bool(items) and not bullet
        if bullet:
            items.append([clean_inline(bullet.group(1)), first_line_no + k])
        elif items and (indented or not bullet):
            items[-1][0] += " " + clean_inline(s.lstrip("> "))
        else:
            items.append([clean_inline(s.lstrip("> ")), first_line_no + k])
    return [(t, n) for t, n in items if t]


def _make_occ(lines, idx, year, its) -> Occurrence:
    date = date_near(lines, idx, year)
    items = []
    for t, ln_no in its:
        said_none, rest = judge_none(t)
        if said_none or not rest:
            continue
        if RESOLVED_ITEM.match(rest):
            continue
        items.append(Item(rest, ln_no, date))
    return Occurrence(idx + 1, date, items, said_none=False)


def extract_occurrences(ctx: Ctx, lines: list, year: int) -> list:
    """Find every place STATUS lists decisions: heading, table column, or `Label:` line."""
    occs: list = []
    i, n, consumed_until = 0, len(lines), -1
    while i < n:
        ln = lines[i]
        if i <= consumed_until:
            i += 1
            continue
        # 1) heading form
        h = heading_of(ln)
        if h:
            title = strip_marks(h[1])
            title_core = re.split(r"[（(：:]", title)[0].strip()
            if ctx.decide_label.match(title_core) or ctx.decide_label.match(title):
                lvl, j, body = h[0], i + 1, []
                while j < n:
                    hh = heading_of(lines[j])
                    if hh and hh[0] <= lvl:
                        break
                    body.append(lines[j])
                    j += 1
                body = [b for b in body if b.strip()]
                occs.append(_make_occ(lines, i, year, items_from_block(body, i + 2)))
                consumed_until = j - 1
            i += 1
            continue
        # 2) table form: a header cell names the decision column
        if ln.lstrip().startswith("|") and i + 1 < n and re.match(r"^\s*\|[\s:|-]+\|\s*$", lines[i + 1]):
            hdr = [c.strip() for c in ln.strip().strip("|").split("|")]
            cols = [k for k, c in enumerate(hdr)
                    if ctx.decide_word.search(c) or ctx.decide_label.match(strip_marks(c))]
            j, rows = i + 2, []
            while j < n and lines[j].lstrip().startswith("|"):
                rows.append((j, [c.strip() for c in lines[j].strip().strip("|").split("|")]))
                j += 1
            if cols:
                its = []
                for rj, cells in rows:
                    for k in cols:
                        if k < len(cells):
                            c = cells[k].strip("* ")
                            if c and c.lower() not in ("-", "—", "无", "/", "否", "no", "none", "n/a"):
                                lead = cells[0].strip("* ") if k != 0 else ""
                                its.append(((lead + ": " if lead else "") + clean_inline(c), rj + 1))
                occs.append(_make_occ(lines, i, year, its))
            consumed_until = j - 1
            i += 1
            continue
        # 3) label form: `Needs decision: ...`
        sl = split_label(ln)
        if sl and ctx.decide_label.match(sl[0]):
            said_none, rest = judge_none(sl[1])
            its: list = []
            if rest:
                its += [(clean_inline(p), i + 1) for p in split_inline(rest)]
            block, j = block_after(ctx, lines, i)
            if not said_none:
                its += items_from_block(block, i + 2)
            occ = _make_occ(lines, i, year, its)
            occ.said_none = said_none and not its
            occs.append(occ)
            consumed_until = j - 1
        i += 1
    return occs


def extract_field(ctx: Ctx, lines: list, names, limit=None) -> list:
    """First occurrence of a field (label line or heading) as excerpt rows."""
    for i, ln in enumerate(lines):
        h = heading_of(ln)
        if h:
            if label_in(strip_marks(h[1]), names):
                lvl, out = h[0], []
                for k in range(i + 1, len(lines)):
                    hh = heading_of(lines[k])
                    if hh and hh[0] <= lvl:
                        break
                    if lines[k].strip():
                        out.append(lines[k].rstrip())
                return out
            continue
        sl = split_label(ln)
        if sl and label_in(sl[0], names) and ln[:1] not in (" ", "\t") and (limit is None or i < limit):
            out = [sl[1]] if sl[1] else []
            block, _ = block_after(ctx, lines, i)
            return out + [b.rstrip() for b in block]
    return []


def render_excerpt(ctx: Ctx, rows: list, max_lines=8, max_chars=320) -> list:
    out = []
    for r in rows[:max_lines]:
        s = re.sub(r"^>\s*", "", r.rstrip())
        if len(s) > max_chars:
            s = s[: max_chars - 1].rstrip() + "…"
        s = re.sub(r"^(\s*)#{1,6}\s+(.*?)\s*$", lambda m: f"{m.group(1)}**{m.group(2).strip('*')}**", s)
        out.append(s)
    if len(rows) > max_lines:
        out.append(ctx.t["more_lines"].format(n=len(rows) - max_lines))
    return out


def first_line_date_head(lines: list) -> str:
    for ln in lines:
        h = heading_of(ln)
        if h and parse_date(h[1])[0]:
            return h[1]
    return ""


def parse_status(ctx: Ctx, root: Path, folder: str, card: str, code: str) -> Status:
    t = ctx.t
    st = Status(folder, card, code, root / folder)
    sp = st.path / ctx.cfg["status_file"]
    if not sp.is_file():
        st.notes.append(t["n_status_missing"])
        return st
    st.exists = True
    lines = read_text(sp).splitlines()
    st.mtime = dt.datetime.fromtimestamp(sp.stat().st_mtime)
    year = st.mtime.year

    # Standard header = everything before the first `##` heading (max 45 lines).
    limit = 45
    for k, ln in enumerate(lines):
        h = heading_of(ln)
        if h and h[0] >= 2:
            limit = min(limit, k)
            break

    for ln in lines[:limit]:
        sl = split_label(ln)
        if sl and label_in(sl[0], UPDATED_LABELS):
            st.updated_raw = sl[1]
            st.updated_date, st.updated_norm = parse_date(sl[1])
            break
    dated_head = first_line_date_head(lines)
    if st.updated_date is None and dated_head:
        st.updated_raw = dated_head
        st.updated_date, st.updated_norm = parse_date(dated_head)
        st.notes.append(t["n_updated_from_head"])
    if st.updated_date is None:
        st.notes.append(t["n_no_updated"])

    stage_rows = extract_field(ctx, lines, STAGE_LABELS, limit)
    st.doing = extract_field(ctx, lines, DOING_LABELS, limit)
    st.next = extract_field(ctx, lines, NEXT_LABELS, limit)
    if not st.doing and any(heading_of(l) and label_in(strip_marks(heading_of(l)[1]), DOING_LABELS)
                            for l in lines):
        st.doing = extract_field(ctx, lines, DOING_LABELS)
    if stage_rows:
        st.stage_full = clean_inline(" ".join(stage_rows))
        st.stage = clip(re.sub(r"\*\*", "", st.stage_full), 60)
    else:
        cand = dated_head
        if not cand:
            for ln in lines[1:]:
                s0 = strip_marks(ln)
                if re.match(r"^(?:\d{4}-)?\d{1,2}-\d{1,2}(?![\d-])", s0) or MONNAME_RE.match(s0):
                    cand = s0
                    break
        st.stage = clip(re.sub(r"\*\*", "", cand), 60) if cand else t["no_stage"]
        st.notes.append(t["n_no_header"] if cand else t["n_no_stage"])
    if not st.doing:
        st.head_excerpt = [l for l in lines[1:] if l.strip()][:10]
        st.notes.append(t["n_no_doing"])

    occs = extract_occurrences(ctx, lines, year)
    if occs:
        # an undated note is ranked at the STATUS update date, not as the oldest
        fallback = st.updated_norm[:10] or "0000-00-00"
        latest = max(occs, key=lambda o: (o.date or fallback, 1 if o.items else 0, o.line))
        st.latest_line, st.latest_date = latest.line, latest.date
        if latest.items:
            st.decide_state, st.latest = "items", latest.items
        else:
            st.decide_state = "none"
        for o in occs:
            if o is not latest:
                st.history += o.items
        if not latest.items and not any(o.items for o in occs):
            st.decide_state = "none"
    else:
        for k, ln in enumerate(lines):
            if ctx.decide_word.search(ln):
                st.weak.append(Item(clip(clean_inline(strip_marks(ln)), 300), k + 1,
                                    date_near(lines, k, year), weak=True))
    for it in st.latest + st.history + st.weak:
        if not it.date:
            it.guess = st.updated_norm[:10]
    if st.decide_state == "unrecognized" and st.weak:
        st.notes.append(t["n_weak"])
    return st


