class Ctx:
    """Per-run settings: language strings and label regexes."""

    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.t = STR.get(cfg["lang"], STR["zh"])
        extra = [re.escape(x) for x in cfg.get("extra_decide_labels", []) if x]
        alt = "|".join([_DECIDE_ZH, _DECIDE_EN] + extra)
        self.decide_label = re.compile(r"^(?:" + alt + r")$", re.I)
        self.decide_word = re.compile(_DECIDE_WORD_ZH + "|" + _DECIDE_WORD_EN, re.I)
        self.known = tuple(x.lower() for x in
                           UPDATED_LABELS + STAGE_LABELS + DOING_LABELS + NEXT_LABELS + OTHER_LABELS)
        self.stale_days = int(cfg["stale_days"])
        self.root = Path(".")  # status root, set by run()
        self.inbox_title = ""


