def split_doc(text: str):
    """Split into (frontmatter lines or None, body)."""
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            fm = text[4:end].split("\n")
            rest = text[end + 4:]
            if rest.startswith("\n"):
                rest = rest[1:]
            return fm, rest
    return None, text


def fm_remove_keys(fm: list, keys) -> list:
    out, skip = [], False
    for ln in fm:
        m = re.match(r"^([^\s#:][^:]*):", ln)
        if m:
            skip = m.group(1).strip() in keys
        elif ln.strip() == "":
            skip = False
        if not skip:
            out.append(ln)
    return out


def fm_has_key(fm: list, key: str) -> bool:
    return any(re.match(rf"^{re.escape(key)}\s*:", ln) for ln in fm)


def yq(v) -> str:
    return str(v) if isinstance(v, int) else json.dumps(v, ensure_ascii=False)


def old_synced(text: str) -> str:
    fm, _ = split_doc(text)
    for ln in fm or []:
        m = re.match(r'^synced:\s*"?([^"]*)"?\s*$', ln)
        if m:
            return m.group(1)
    return ""


def item_md(ctx: Ctx, it: Item) -> str:
    t = ctx.t
    when = it.date or (t["about"] + it.guess if it.guess else t["undated"])
    return f"{clip(it.text, 320)} (L{it.line} · {when})"


def links_md(ctx: Ctx, st: Status) -> list:
    out = []
    for name in ctx.cfg["link_targets"]:
        p = st.path / name
        if p.exists():
            out.append("- " + file_ref(ctx, p, name + ("/" if p.is_dir() else "")))
    return out


def none_text(ctx: Ctx, st: Status) -> str:
    where = f"L{st.latest_line}" + (f" · {st.latest_date}" if st.latest_date else "")
    return ctx.t["none_text"].format(where=where)


def build_auto_block(ctx: Ctx, st: Status) -> str:
    t = ctx.t
    L = [AUTO_BEGIN, t["auto_note"], ""]
    if not st.exists:
        return "\n".join(L + [t["missing"], AUTO_END])
    stage_txt = re.sub(r"\*\*", "", st.stage_full) if st.stage_full.count("**") % 2 else st.stage_full
    L += [f"### {t['stage']}", clip(stage_txt or st.stage or t["unrecognized"], 500), ""]
    L += [f"### {t['doing']}"]
    if st.doing:
        L += render_excerpt(ctx, st.doing)
    elif st.head_excerpt:
        L += [t["fallback_doing"]] + render_excerpt(ctx, st.head_excerpt, 10)
    else:
        L += [t["unrecognized"]]
    L += ["", f"### {t['decide']}"]
    if st.decide_state == "items":
        L += [f"- {item_md(ctx, it)}" for it in st.latest[:12]]
        if len(st.latest) > 12:
            L.append(t["more_items"].format(n=len(st.latest) - 12))
    elif st.decide_state == "none":
        L += [none_text(ctx, st)]
    else:
        L += [t["unrecognized"]]
        L += [f"- {t['weak']}: {item_md(ctx, it)}" for it in st.weak[:3]]
    if st.history and st.decide_state != "unrecognized":
        L += ["", t["history"].format(n=len(st.history))]
        L += [f"> - {item_md(ctx, it)}" for it in st.history[:15]]
    L += ["", f"### {t['next']}"]
    L += render_excerpt(ctx, st.next) if st.next else [t["unrecognized"]]
    L += ["", f"### {t['links']}"] + links_md(ctx, st)
    if st.notes:
        L += ["", t["hints"]] + [f"> - {n}" for n in st.notes]
    L.append(AUTO_END)
    return "\n".join(L)


def build_card(ctx: Ctx, st: Status, existing, synced: str) -> str:
    my_notes = f"## {ctx.t['my_notes']}"
    tag_line = f"tags: [project/{ctx.cfg['acronym']}, status-card]"
    managed = {
        "status_code": st.code, "title": st.card, "status_stage": st.stage,
        "status_updated": st.updated_norm or st.updated_raw or "",
        "status_mtime": st.mtime.strftime("%Y-%m-%d %H:%M") if st.mtime else "",
        "status_path": rel_posix(st.path, ctx.root),  # relative to status_root: no user name in the vault
        "decisions_open": len(st.latest) if st.decide_state == "items" else 0,
        "synced": synced,
    }
    block = build_auto_block(ctx, st)
    if existing is None:
        fm = [tag_line] + [f"{k}: {yq(managed[k])}" for k in MANAGED_KEYS]
        return "---\n" + "\n".join(fm) + "\n---\n\n" + f"# {st.card}\n\n" + block + f"\n\n{my_notes}\n\n"
    fm, body = split_doc(existing)
    fm = fm_remove_keys(fm or [], set(MANAGED_KEYS))
    if not fm_has_key(fm, "tags"):
        fm.insert(0, tag_line)
    fm += [f"{k}: {yq(managed[k])}" for k in MANAGED_KEYS]
    b, e = body.find(AUTO_BEGIN), body.find(AUTO_END)
    if b != -1 and e != -1 and e > b:
        body = body[:b] + block + body[e + len(AUTO_END):]
    else:  # markers were deleted: re-insert after the title, keep all existing text
        m = re.match(r"^(\s*# [^\n]*\n)?", body)
        head = m.group(0) if m else ""
        body = head + "\n" + block + "\n" + body[len(head):]
        if my_notes not in body:
            body = body.rstrip("\n") + f"\n\n{my_notes}\n\n"
    return "---\n" + "\n".join(fm) + "\n---\n" + ("\n" if not body.startswith("\n") else "") + body


def checked_texts(existing) -> set:
    out = set()
    for ln in (existing or "").splitlines():
        m = re.match(r"^- \[[xX]\] (.*?)(?:\s*〔.*)?$", ln)
        if m:
            out.add(m.group(1).strip())
    return out


def fmt_dt(ctx: Ctx, st: Status) -> str:
    a = st.updated_norm or ctx.t["unwritten"]
    b = st.mtime.strftime("%m-%d %H:%M") if st.mtime else "—"
    return ctx.t["status_written"].format(a=a, b=b)


def build_inbox(ctx: Ctx, sts: list, existing, synced: str) -> str:
    t = ctx.t
    done = checked_texts(existing)
    L = ["---", f"tags: [project/{ctx.cfg['acronym']}, status-dashboard]", f"synced: {yq(synced)}", "---", "",
         f"# {ctx.inbox_title}", "", GEN_MARK, "", t["inbox_desc1"], t["inbox_desc2"], t["inbox_desc3"], "", "@@TOTAL@@", ""]
    total = 0
    for st in sts:
        link = file_ref(ctx, st.path / ctx.cfg["status_file"], t["src"])
        L += [f"## [[{st.card}]]", f"{fmt_dt(ctx, st)} · {link}", ""]
        if not st.exists:
            L += [t["inbox_none_file"], ""]
            continue
        if st.decide_state == "items":
            for it in st.latest:
                txt = clip(it.text, 400)
                box = "x" if txt in done else " "
                when = it.date or (t["about"] + it.guess if it.guess else t["undated"])
                L.append(f"- [{box}] {txt} 〔L{it.line} · {when}〕")
                total += 1
        elif st.decide_state == "none":
            L.append(none_text(ctx, st))
        else:
            L.append(t["inbox_unrec"].format(link=link))
            L += [f"- {t['inbox_weak']}: {item_md(ctx, it)}" for it in st.weak[:3]]
        if st.history and st.decide_state != "unrecognized":
            L += ["", t["history2"].format(n=len(st.history))]
            L += [f"> - {item_md(ctx, it)}" for it in st.history[:20]]
        L.append("")
    L[L.index("@@TOTAL@@")] = t["inbox_total"].format(n=total)
    return "\n".join(L).rstrip() + "\n"


def staleness(ctx: Ctx, st: Status, today: dt.date):
    cands = [d for d in (st.updated_date, st.mtime.date() if st.mtime else None) if d]
    if not cands:
        return True, ctx.t["no_date"]
    age = (today - max(cands)).days
    return age > ctx.stale_days, ctx.t["ago"].format(n=age)


def build_board(ctx: Ctx, sts: list, root: Path, synced: str, today: dt.date) -> str:
    t = ctx.t
    L = ["---", f"tags: [project/{ctx.cfg['acronym']}, status-dashboard]", f"synced: {yq(synced)}", "---", "",
         f"# {ctx.cfg.get('series_title') or t['board_title']}", "", GEN_MARK, "", t["board_desc"], "",
         f"[[{ctx.inbox_title}]]", "", f"## {t['overview']}", "", f"![[{ctx.cfg['base_name']}]]", "",
         f"## {t['brief']}", "", t["stale_legend"].format(n=ctx.stale_days), "",
         t["cols"], "|---|---|---|---|---|---|"]
    for st in sts:
        stale, why = staleness(ctx, st, today)
        flag = "⚠️ " + why if stale else why
        lag = ""
        if st.updated_date and st.mtime and (st.mtime.date() - st.updated_date).days > 1:
            lag = t["lag"]
        dec = (str(len(st.latest)) if st.decide_state == "items"
               else "0" if st.decide_state == "none" else t["unrec_short"])
        stage = (st.stage or "—").replace("|", "/")
        L.append(f"| [[{st.card}]] | {stage} | {st.updated_norm or t['unwritten']}{lag} | "
                 f"{st.mtime.strftime('%m-%d %H:%M') if st.mtime else '—'} | {dec} | {flag} |")
    ov = ctx.cfg.get("overview_file")
    if ov:
        L += ["", f"## {ctx.cfg.get('overview_label') or t['overview_h']}", ""]
        bp = root / ov
        if bp.is_file():
            written, wn = None, ""
            for ln in read_text(bp).splitlines()[:15]:
                sl = split_label(ln)
                if sl and label_in(sl[0], UPDATED_LABELS):
                    written, wn = parse_date(sl[1])
                    break
            mt = dt.datetime.fromtimestamp(bp.stat().st_mtime)
            newest = [max(d for d in (s.updated_date, s.mtime.date() if s.mtime else None) if d)
                      for s in sts if s.exists and (s.updated_date or s.mtime)]
            newest_paper = max(newest) if newest else None
            L.append(t["ov_file"].format(ref=file_ref(ctx, bp, Path(ov).name)))
            L.append(t["ov_times"].format(w=wn or t["unwritten"], m=mt.strftime("%Y-%m-%d %H:%M")))
            base = max(d for d in (written, mt.date()) if d)
            lag_days = (today - base).days
            behind = (newest_paper - base).days if newest_paper else 0
            if lag_days > ctx.stale_days or behind > ctx.stale_days:
                L.append(t["ov_stale"].format(d=lag_days, b=max(behind, 0)))
            else:
                L.append(t["ov_fresh"].format(d=lag_days))
        else:
            L.append(t["ov_missing"].format(name=ov))
    return "\n".join(L) + "\n"


