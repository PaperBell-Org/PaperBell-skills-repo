def read_text(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def file_url(p: Path) -> str:
    return "file://" + quote(str(p))


def rel_posix(p: Path, root: Path) -> str:
    """Path relative to the status root (no user name, no machine-specific prefix)."""
    try:
        return p.relative_to(root).as_posix()
    except ValueError:
        return p.name


def file_ref(ctx: "Ctx", p: Path, label: str) -> str:
    """A file:// link only when `link_files` is on; otherwise the relative path as code."""
    if ctx.cfg.get("link_files"):
        return f"[{label}]({file_url(p)})"
    rel = rel_posix(p, ctx.root)
    return f"{label} (`{rel}`)" if rel != label else f"`{rel}`"


def clip(s: str, n: int) -> str:
    s = s.strip()
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def clean_inline(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def norm_date(m: re.Match) -> str:
    d = f"{int(m.group(1)):04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"
    return d + (" " + m.group(4).zfill(5) if m.group(4) else "")


def parse_date(s: str):
    m = DATE_RE.search(s)
    if m:
        try:
            return dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3))), norm_date(m)
        except ValueError:
            return None, None
    m = MONNAME_RE.search(s)
    if m and m.group(5):
        day = m.group(1) or m.group(4)
        mon = MONTHS[(m.group(2) or m.group(3)).lower()[:3]]
        try:
            d = dt.date(int(m.group(5)), mon, int(day))
        except ValueError:
            return None, None
        return d, d.isoformat()
    return None, None


def strip_marks(line: str) -> str:
    """Drop leading quote / list / number / bold marks so labels can be recognised."""
    s = line.strip()
    while True:
        n = re.sub(r"^(?:>\s*|[-*+]\s+|\d+[.)、）]\s*|【|\*\*|__)", "", s)
        if n == s:
            break
        s = n
    return s


def split_label(line: str):
    """Recognise `Label: content` (also with ** or 】 after the label)."""
    s = strip_marks(line)
    m = re.match(r"^([^：:\n]{1,40}?)(?:\*\*|__|】)*[：:]\s*(?:\*\*|__)?(.*)$", s)
    if not m:
        return None
    return m.group(1).strip().strip("*_ "), m.group(2).strip()


def heading_of(line: str):
    m = re.match(r"^(#{1,6})\s+(.*\S)\s*$", line)
    return (len(m.group(1)), m.group(2)) if m else None


def label_in(label: str, names) -> bool:
    low = label.lower()
    return any(low.startswith(n.lower()) for n in names)


def is_known_label_line(ctx: Ctx, line: str) -> bool:
    if line[:1] in (" ", "\t"):
        return False
    sl = split_label(line)
    if not sl:
        return False
    lab = sl[0]
    return any(lab.lower().startswith(k) for k in ctx.known) or bool(ctx.decide_label.match(lab))


