#!/usr/bin/env python3
"""One-way sync: project STATUS.md files (outside the vault) -> vault dashboard.

Reads every project's STATUS.md (read-only) and writes, inside the CIMPO
project folder named in the config (40 - Projects/<name>/) only:

  * one project card per project   (<card>.md)
  * one decisions inbox            (<inbox_name>.md, rewritten every run)
  * one dashboard page             (<board_name>.md, rewritten every run)
  * one Base view                  (<base_name>.base)

Card rules: frontmatter keys this script manages are updated, every other key
is kept; the body is replaced only between the AUTO:BEGIN / AUTO:END markers;
everything outside the markers (the hand-written area) is never touched.
Re-running with unchanged inputs changes nothing (idempotent).

Safety: the project folder must already exist inside a vault (a folder with
`.obsidian/`) and hold its home note `<name>.md` whose `acronym` matches the
config. Every target must resolve inside that folder, must not be a symbolic
link, and, if it already exists, must carry this script's marks (tag
`status-card` / `status-dashboard`, the AUTO markers, or the generator comment
on the first line of a `.base`). Otherwise nothing is written.

Standard library only.

    python3 <skill dir>/scripts/sync_status.py --vault <vault root> --config <config.json>
    python3 <skill dir>/scripts/sync_status.py --vault <vault root> --config <config.json> --dry-run
"""
