class SyncError(ValueError):
    """Refusal to write: unsafe target, foreign file, or missing project folder."""


UNSAFE_CHARS = re.compile(r'[\\/:*?"<>|\x00-\x1f]')


def check_name(kind: str, name: str, suffix: str = "") -> str:
    """A plain file name: no separators or reserved characters, no `..`, not absolute."""
    if not isinstance(name, str) or not name.strip():
        raise ValueError(f"config: {kind} must be a non-empty name")
    if name != name.strip():
        raise ValueError(f"config: {kind} has leading or trailing spaces: {name!r}")
    if Path(name).is_absolute() or name.startswith("~"):
        raise ValueError(f"config: {kind} must be a plain file name, not a path: {name}")
    if ".." in name or name.startswith("."):
        raise ValueError(f"config: {kind} must not contain `..` or start with `.`: {name}")
    if UNSAFE_CHARS.search(name):
        raise ValueError(f'config: {kind} has characters unsafe for file names (\\ / : * ? " < > |): {name}')
    if suffix and not name.lower().endswith(suffix):
        raise ValueError(f"config: {kind} must end with {suffix}: {name}")
    return name


def fm_tags(text: str) -> set:
    """Tags from the frontmatter (inline list, block list or a single value)."""
    fm, _ = split_doc(text)
    tags, in_tags = set(), False
    for ln in fm or []:
        m = re.match(r"^tags\s*:\s*(.*)$", ln)
        if m:
            in_tags = True
            v = m.group(1).strip()
            if v:
                tags.update(x.strip().strip("'\"#") for x in v.strip("[]").split(","))
                in_tags = False
            continue
        if in_tags:
            m = re.match(r"^\s+-\s*(.+)$", ln)
            if m:
                tags.add(m.group(1).strip().strip("'\"#"))
            elif ln.strip():
                in_tags = False
    return {t for t in tags if t}


def owned_by_script(name: str, text: str) -> bool:
    """True when an existing file was written by this script and may be rewritten."""
    if name.endswith(".base"):
        return text.split("\n", 1)[0].strip() == BASE_MARK
    return bool(fm_tags(text) & set(OWN_TAGS)) or "<!-- AUTO:" in text


def fm_value(text: str, key: str) -> str:
    fm, _ = split_doc(text)
    for ln in fm or []:
        m = re.match(rf"^{re.escape(key)}\s*:\s*(.*?)\s*$", ln)
        if m:
            return m.group(1).strip().strip("'\"")
    return ""


def check_project_folder(cfg: dict, vault: Path) -> Path:
    """The vault has `.obsidian/`; the project folder exists inside it with a matching home note."""
    vault_r = vault.resolve()
    if not (vault_r / ".obsidian").is_dir():
        raise SyncError(f"not an Obsidian vault (no .obsidian/ folder): {vault_r}")
    pf = cfg["project_folder"]
    if Path(pf).is_absolute():
        raise SyncError("project_folder must be a vault-relative path")
    out_dir = (vault_r / pf).resolve()
    if vault_r not in out_dir.parents:
        raise SyncError("project_folder must stay inside the vault")
    if not out_dir.is_dir():
        raise SyncError(f"project folder does not exist: {pf}. Create the CIMPO project first "
                        "(home note <name>/<name>.md with an `acronym`); the script never creates folders.")
    home = out_dir / f"{out_dir.name}.md"
    if not home.is_file():
        raise SyncError(f"project home note not found: {pf}/{out_dir.name}.md")
    acr = fm_value(read_text(home), "acronym")
    if acr != cfg["acronym"]:
        raise SyncError(f"acronym mismatch: home note says {acr or '(none)'!r}, config says {cfg['acronym']!r}")
    return out_dir


def check_target(out_dir: Path, name: str) -> Path:
    """Refuse symlinks, paths that leave the project folder, and files the script did not write."""
    p = out_dir / name
    if p.is_symlink():
        raise SyncError(f"refusing to write through a symbolic link: {name}")
    if p.resolve().parent != out_dir or out_dir not in p.resolve().parents:
        raise SyncError(f"target leaves the project folder: {name}")
    if p.exists():
        if not p.is_file():
            raise SyncError(f"target exists and is not a file: {name}")
        if not owned_by_script(name, read_text(p)):
            raise SyncError(
                f"{name} already exists and was not written by this script (no status-card / "
                "status-dashboard tag, no AUTO marker, no generator comment). Rename the card, "
                "inbox_name, board_name or base_name in the config, or move the existing note.")
    return p


def write_if_changed(path: Path, new: str, existing, dry: bool) -> str:
    """Skip the write when content is unchanged (ignoring the `synced` stamp)."""
    if existing is not None:
        a = re.sub(r"^synced: .*$", "synced: X", existing, flags=re.M)
        b = re.sub(r"^synced: .*$", "synced: X", new, flags=re.M)
        if a == b:
            return "unchanged"
    if not dry:
        path.write_text(new, encoding="utf-8")
    return "updated" if existing is not None else "created"


def load_config(path: Path) -> dict:
    cfg = dict(DEFAULTS)
    cfg.update(json.loads(path.read_text(encoding="utf-8")))
    for key in ("project_folder", "acronym"):
        if not cfg.get(key):
            raise ValueError(f"config is missing required key: {key}")
    if not re.fullmatch(r"[\w.-]+", cfg["acronym"]):
        raise ValueError("config: acronym may only contain letters, digits, _ . -")
    if not cfg.get("projects"):
        raise ValueError("config: `projects` must list at least one project")
    if not isinstance(cfg.get("link_files"), bool):
        raise ValueError("config: link_files must be true or false")
    check_name("base_name", cfg["base_name"], ".base")
    for key in ("inbox_name", "board_name"):
        if cfg.get(key) not in (None, ""):
            check_name(key, cfg[key])
    cfg["projects"] = [dict(p) for p in cfg["projects"]]
    for p in cfg["projects"]:
        if not p.get("folder") or not p.get("card"):
            raise ValueError("config: every project needs `folder` and `card`")
        p.setdefault("code", p["card"].split()[0])
        check_name("card", p["card"])
    return cfg


def check_names(cfg: dict, out_dir: Path, inbox: str, board: str):
    """Cards must not collide with the home note, the inbox, the board or each other."""
    reserved = {out_dir.name.casefold(): "the project home note",
                inbox.casefold(): "inbox_name", board.casefold(): "board_name"}
    if inbox.casefold() == board.casefold():
        raise SyncError("config: inbox_name and board_name must differ")
    if out_dir.name.casefold() in (inbox.casefold(), board.casefold()):
        raise SyncError("config: inbox_name / board_name must differ from the project folder name")
    seen = set()
    for p in cfg["projects"]:
        key = p["card"].casefold()
        if key in reserved:
            raise SyncError(f"config: card name {p['card']!r} collides with {reserved[key]}; rename the card")
        if key in seen:
            raise SyncError(f"config: duplicate card name {p['card']!r}")
        seen.add(key)


def run(cfg: dict, vault: Path, status_root: Path, dry: bool = False, now: dt.datetime | None = None):
    ctx = Ctx(cfg)
    ctx.root = status_root
    ctx.inbox_title = cfg.get("inbox_name") or ctx.t["default_inbox"]
    board_name = cfg.get("board_name") or ctx.t["default_board"]
    out_dir = check_project_folder(cfg, vault)
    check_names(cfg, out_dir, ctx.inbox_title, board_name)
    now = now or dt.datetime.now()
    synced, today = now.strftime("%Y-%m-%d %H:%M"), now.date()

    sts = [parse_status(ctx, status_root, p["folder"], p["card"], p["code"]) for p in cfg["projects"]]
    jobs = [(f"{st.card}.md", lambda ex, s, st=st: build_card(ctx, st, ex, s)) for st in sts]
    jobs += [(f"{ctx.inbox_title}.md", lambda ex, s: build_inbox(ctx, sts, ex, s)),
             (f"{board_name}.md", lambda ex, s: build_board(ctx, sts, status_root, s, today)),
             (cfg["base_name"], lambda ex, s: build_base(ctx))]
    # check every target before writing anything
    targets = [(check_target(out_dir, name), name, build) for name, build in jobs]
    results = []
    for p, name, build in targets:
        p = check_target(out_dir, name)  # re-check right before the write
        existing = read_text(p) if p.exists() else None
        r = write_if_changed(p, build(existing, old_synced(existing) if existing else synced), existing, dry)
        if r == "updated" and not dry:  # refresh the stamp only on real change
            p.write_text(build(existing, synced), encoding="utf-8")
        results.append((name, r))
    return ctx, out_dir, sts, results


def resolve_cfg_path(arg: Path, vault: Path) -> Path:
    if arg.is_file():
        return arg.resolve()
    alt = vault / arg
    if alt.is_file():
        return alt.resolve()
    raise FileNotFoundError(f"config not found: {arg}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="One-way sync of project STATUS.md files into a vault dashboard")
    ap.add_argument("--config", type=Path, required=True,
                    help="JSON config (absolute, relative to cwd, or relative to --vault)")
    ap.add_argument("--vault", type=Path, required=True, help="vault root (the folder that contains .obsidian/)")
    ap.add_argument("--status-root", type=Path, default=None,
                    help="folder holding the project folders; overrides `status_root` in the config")
    ap.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    a = ap.parse_args(argv)

    vault = a.vault.resolve()
    try:
        cfg = load_config(resolve_cfg_path(a.config, vault))
    except (OSError, ValueError, json.JSONDecodeError) as e:
        print(f"config error: {e}", file=sys.stderr)
        return 2
    root_arg = a.status_root or cfg.get("status_root")
    if not root_arg:
        print("config error: set `status_root` in the config or pass --status-root", file=sys.stderr)
        return 2
    root = Path(root_arg)
    root = (root if root.is_absolute() else vault / root).resolve()
    if not root.is_dir():
        print(f"status root not found: {root}", file=sys.stderr)
        return 2
    try:
        ctx, out_dir, sts, results = run(cfg, vault, root, a.dry_run)
    except SyncError as e:
        print(f"refused: {e}", file=sys.stderr)
        return 2
    except ValueError as e:
        print(f"config error: {e}", file=sys.stderr)
        return 2
    t = ctx.t
    print(f"{'[dry-run] ' if a.dry_run else ''}{t['out_dir']}: {out_dir}")
    for n, r in results:
        print(f"  {r:<9} {n}")
    print(f"{t['summary']}:")
    for st in sts:
        if not st.exists:
            print(f"  {st.card}: {t['missing_short']}")
            continue
        extra = f"; {'; '.join(st.notes)}" if st.notes else ""
        print("  " + t["summary_line"].format(
            card=st.card, state=st.decide_state, n=len(st.latest), h=len(st.history), w=len(st.weak),
            stage=t["has"] if st.stage_full else t["fallback"], doing=t["has"] if st.doing else t["no"],
            nxt=t["has"] if st.next else t["no"]) + extra)
    return 0


if __name__ == "__main__":
    sys.exit(main())
